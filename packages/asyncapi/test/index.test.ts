import { fileURLToPath } from 'node:url';
import { describe, expect, test } from 'vitest';
import { generateFilesOnly } from '@/generate-file';
import { createAsyncAPI } from '@/server';
import path from 'node:path';

const cwd = fileURLToPath(new URL('./', import.meta.url));

function stringifyOutput(files: { path: string; content: string }[]) {
  return files
    .sort((a, b) => a.path.localeCompare(b.path))
    .map((file) => `## ${file.path}\n\n${file.content}`)
    .join('\n\n');
}

describe('Generate AsyncAPI documents', () => {
  test('Streetlights (Per Operation)', async () => {
    const out = await generateFilesOnly({
      input: createAsyncAPI({
        input: {
          streetlights: path.join(cwd, './fixtures/streetlights.yaml'),
        },
      }),
      per: 'operation',
    });

    expect(out).toHaveLength(2);
    expect(out).toMatchInlineSnapshot(`
      [
        {
          "content": "---
      title: Receive light measurement
      full: true
      _asyncapi:
        preload:
          - streetlights
        action: receive
        toc: []
        structuredData:
          headings:
            - content: Light measured
              id: messages.lightmeasuredmessage
          contents:
            - content: Inform about environmental lighting conditions
              heading: messages.lightmeasuredmessage
      ---

      {/* This file was generated by Fumadocs. Do not edit this file directly. Any changes should be made by running the generation command again. */}

      <AsyncAPIPage document="streetlights" operations={[{"id":"receiveLightMeasurement","action":"receive"}]} />",
          "path": "receiveLightMeasurement.mdx",
        },
        {
          "content": "---
      title: Send light measurement
      full: true
      _asyncapi:
        preload:
          - streetlights
        action: send
        toc: []
        structuredData:
          headings:
            - content: Light measured
              id: messages.lightmeasuredmessage
          contents:
            - content: Inform about environmental lighting conditions
              heading: messages.lightmeasuredmessage
      ---

      {/* This file was generated by Fumadocs. Do not edit this file directly. Any changes should be made by running the generation command again. */}

      <AsyncAPIPage document="streetlights" operations={[{"id":"sendLightMeasurement","action":"send"}]} />",
          "path": "sendLightMeasurement.mdx",
        },
      ]
    `);
  });

  test('Streetlights (Per Tag)', async () => {
    const out = await generateFilesOnly({
      input: createAsyncAPI({
        input: {
          streetlights: path.join(cwd, './fixtures/streetlights.yaml'),
        },
      }),
      per: 'tag',
    });

    expect(out).toMatchInlineSnapshot(`
      [
        {
          "content": "---
      title: Lighting
      description: Operations related to streetlights
      full: true
      _asyncapi:
        preload:
          - streetlights
        toc:
          - depth: 2
            title: Receive light measurement
            url: '#receive-light-measurement'
          - depth: 2
            title: Send light measurement
            url: '#send-light-measurement'
        structuredData:
          headings:
            - content: Receive light measurement
              id: receive-light-measurement
            - content: Light measured
              id: receive-light-measurement.messages.lightmeasuredmessage
            - content: Send light measurement
              id: send-light-measurement
            - content: Light measured
              id: send-light-measurement.messages.lightmeasuredmessage
          contents:
            - content: Inform about environmental lighting conditions
              heading: receive-light-measurement.messages.lightmeasuredmessage
            - content: Inform about environmental lighting conditions
              heading: send-light-measurement.messages.lightmeasuredmessage
      ---

      {/* This file was generated by Fumadocs. Do not edit this file directly. Any changes should be made by running the generation command again. */}

      <AsyncAPIPage document="streetlights" operations={[{"id":"receiveLightMeasurement","action":"receive"},{"id":"sendLightMeasurement","action":"send"}]} showTitle />",
          "path": "lighting.mdx",
        },
      ]
    `);
  });

  test('Streetlights (Per File)', async () => {
    const out = await generateFilesOnly({
      input: createAsyncAPI({
        input: {
          streetlights: path.join(cwd, './fixtures/streetlights.yaml'),
        },
      }),
      per: 'file',
    });

    expect(out).toHaveLength(1);
    expect(out[0].path).toContain('streetlights');
    expect(stringifyOutput(out)).toMatchSnapshot();
  });

  test('Streetlights (with imports)', async () => {
    const out = await generateFilesOnly({
      input: createAsyncAPI({
        input: {
          streetlights: path.join(cwd, './fixtures/streetlights.yaml'),
        },
      }),
      per: 'file',
      imports: [
        { names: ['API_BASE_URL', 'Foo'], from: '@/constants' },
        { names: ['Bar'], from: '@/components/bar' },
      ],
    });

    expect(out).toHaveLength(1);
    expect(out[0].content).toContain(
      'import { API_BASE_URL, Foo } from "@/constants";\nimport { Bar } from "@/components/bar";\n\n',
    );
  });

  test('Streetlights (with empty imports)', async () => {
    const options = {
      input: createAsyncAPI({
        input: {
          streetlights: path.join(cwd, './fixtures/streetlights.yaml'),
        },
      }),
      per: 'file',
    } as const;

    expect(await generateFilesOnly({ ...options, imports: [] })).toEqual(
      await generateFilesOnly(options),
    );
  });

  test('throws error when no input files found', async () => {
    await expect(
      generateFilesOnly({
        input: createAsyncAPI({ input: {} }),
        per: 'file',
      }),
    ).rejects.toThrow();
  });
});

describe('createAsyncAPI()', () => {
  const file = path.join(cwd, './fixtures/streetlights.yaml');

  test('sources work without `this`', async () => {
    const { staticSource } = createAsyncAPI({ input: { streetlights: file } });
    const { files } = await staticSource({ per: 'file' });

    expect(files.map((item) => item.path)).toEqual(['/streetlights.mdx']);
  });

  test('watches the input files', () => {
    expect(createAsyncAPI({ input: { streetlights: file } })._getWatchPaths()).toEqual([file]);
    expect(
      createAsyncAPI({ input: [file, 'https://example.com/asyncapi.yaml'] })._getWatchPaths(),
    ).toEqual([file]);
  });
});
