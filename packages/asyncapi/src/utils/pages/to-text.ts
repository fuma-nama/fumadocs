import type { AsyncAPIObject, TagObject } from '@/types';
import { stringify } from 'yaml';
import {
  type GeneratedPageProps,
  getPageProps,
  type OperationOutput,
  type PageOutput,
} from '@/utils/pages/builder';
import type { InternalAsyncAPIMeta } from '@/server';
import { toStaticData } from '@/utils/pages/to-static-data';
import { doubleQuote } from '@/utils/string-utils';

export interface PagesToTextOptions {
  imports?: {
    names: string[];
    from: string;
  }[];
  frontmatter?: (
    title: string,
    description: string | undefined,
    context: DocumentContext,
  ) => Record<string, unknown>;
  includeDescription?: boolean;
  addGeneratedComment?: boolean | string;
}

export function toText(
  entry: PageOutput | OperationOutput,
  doc: AsyncAPIObject,
  options: PagesToTextOptions = {},
) {
  const { frontmatter, includeDescription = false } = options;
  const extend = frontmatter?.(
    entry.info.title,
    entry.info.description,
    entry.type === 'page'
      ? entry.tag
        ? { type: 'tag', tag: entry.tag }
        : { type: 'file' }
      : { type: 'operation' },
  );
  const pageProps = getPageProps(entry);
  if (!includeDescription) pageProps.showDescription = false;

  const meta: InternalAsyncAPIMeta = {
    preload: [entry.schemaId],
    action: entry.type === 'operation' ? entry.item.action : undefined,
  };

  return generateDocument(
    {
      title: entry.info.title,
      description: includeDescription ? undefined : entry.info.description,
      full: true,
      ...extend,
      _asyncapi: {
        ...meta,
        ...toStaticData(pageProps, doc),
        ...(extend?._asyncapi as object | undefined),
      },
    },
    pageContent(pageProps),
    options,
  );
}

export function generateDocument(
  frontmatter: unknown,
  content: string,
  { addGeneratedComment = true, imports }: PagesToTextOptions,
): string {
  const out: string[] = [];
  const banner = stringify(frontmatter, {
    compat: 'yaml-1.1',
    singleQuote: true,
  }).trimEnd();
  if (banner.length > 0) out.push(`---\n${banner}\n---`);

  if (addGeneratedComment) {
    const comment =
      typeof addGeneratedComment === 'string'
        ? addGeneratedComment
        : 'This file was generated by Fumadocs. Do not edit this file directly. Any changes should be made by running the generation command again.';

    out.push(`{/* ${comment.replaceAll('/', '\\/')} */}`);
  }

  if (imports && imports.length > 0) {
    let lines = '';
    for (const item of imports)
      lines += `${lines && '\n'}import { ${item.names.join(', ')} } from ${doubleQuote(item.from)};`;
    out.push(lines);
  }

  out.push(content);
  return out.join('\n\n');
}

export type DocumentContext =
  | {
      type: 'tag';
      tag: TagObject;
    }
  | {
      type: 'operation';
    }
  | {
      type: 'file';
    };

function pageContent({
  showTitle,
  showDescription,
  document,
  operations,
}: GeneratedPageProps): string {
  let out = `<AsyncAPIPage document=${doubleQuote(document)}`;
  // only the fields of `OperationItem`
  if (operations) out += ` operations={${JSON.stringify(operations, ['id', 'action'])}}`;
  if (showTitle) out += ' showTitle';
  if (showDescription) out += ' showDescription';

  return `${out} />`;
}
