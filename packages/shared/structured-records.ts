import { hasParts, listCode, type CodeNode } from './code-output';
import { headingIdRegex, type HeadingIds } from './heading-id';

interface Range {
  start: number;
  end: number;
}

/** a content of structured data, see `fumadocs-core/mdx-plugins/remark-structure` */
interface StructuredContent {
  heading: string | undefined;
  content: string;
  table?: string;
}

/** a heading of structured data, `code` is its ID as code */
interface StructuredHeading {
  id: string;
  code?: string;
  content: string;
}

/** the code output of a compiler for search, as the records use it */
interface RecordOutput<N> {
  s: {
    source: string;
    inner(node: N): string;
    stringify(node: N): string;
    within(range: Range, outer: Range): boolean;
  };
  range(node: N): Range | undefined;
  edit(node: N): void;
  toStatic(text: string): string;
  toCode(text: string): string;
  componentsCode(scope: () => ReadonlySet<string>, from: string): string;
}

interface StructuredRecordsOptions<N> {
  /** whether a node is a record */
  isType: (node: N) => boolean;
  /** whether a JSX element with content on several lines is a record as a whole */
  mdxTypes: (node: N) => boolean;
  /** `tableRowToStructuredData()` of `fumadocs-core/search` */
  tableRow: (row: { table: string; row: string[]; header: string[] }) => StructuredContent;
  /** the IDs of headings from code */
  headingIds?: HeadingIds;
}

/**
 * The records of structured data of a document, in document order: slices of its Markdown for search, see the
 * `target` of the code output.
 */
export function createStructuredRecords<N extends CodeNode>(
  out: RecordOutput<N>,
  { isType, mdxTypes, tableRow, headingIds }: StructuredRecordsOptions<N>,
) {
  const { s } = out;
  const records: ((StructuredHeading | StructuredContent) & { when: string[] })[] = [];
  /** records are stringified after the edits of every node */
  const pending: (() => void)[] = [];
  let covered: Range | undefined;
  let tables = 0;
  /** whether a record reads the props of a page */
  let dynamic = false;

  const push = (item: StructuredHeading | StructuredContent, when: string[] = []) => {
    if (when.length > 0 || ('code' in item && item.code) || hasParts(item.content)) dynamic = true;
    records.push({ ...item, when });
  };
  const cells = (row: { children: N[] }) => {
    const cells: string[] = [];
    for (const cell of row.children) cells.push(s.inner(cell).trim());
    return cells;
  };
  const flush = () => {
    for (const record of pending) record();
    pending.length = 0;
  };
  return {
    /** `when`: the conditions of the branches of `<show>` around it */
    push,
    /**
     * Edit a node for records, and record it when it is one.
     *
     * @param when - read the conditions of the branches of `<show>` around the node
     */
    collect(node: N, when: () => string[]): void {
      const { type } = node;
      const isElement = type === 'mdxJsxFlowElement' || type === 'mdxJsxTextElement';
      out.edit(node);

      const { data } = node as {
        data?: {
          hProperties?: { id?: unknown };
          structuredData?: { contents: StructuredContent[] };
        } | null;
      };
      if (data?.structuredData) {
        const items = data.structuredData.contents;
        const conditions = when();
        pending.push(() => {
          for (const item of items) push(item, conditions);
        });
        covered = out.range(node) ?? covered;
        return;
      }
      if (!isType(node)) return;

      // nodes without a source, generated by plugins, and nodes in a record aren't records
      const range = out.range(node);
      if (!range || (covered && s.within(range, covered))) return;
      // an element on one line has inline content, recorded like a paragraph
      const line = s.source.indexOf('\n', range.start);
      if (isElement && line !== -1 && line < range.end && !mdxTypes(node)) return;
      covered = range;
      const conditions = when();

      if (type === 'table') {
        const table = `table-${tables++}`;
        pending.push(() => {
          // read here only: reading the children of a node has a cost in Sätteri
          const [head, ...rows] = (node as unknown as { children: { children: N[] }[] }).children;
          const header = cells(head);
          for (const row of rows) push(tableRow({ table, row: cells(row), header }), conditions);
        });
      } else if (type === 'heading') {
        const id = data?.hProperties?.id;
        if (typeof id !== 'string') {
          console.warn(
            '[remark-structure] hProperties.id is missing in heading node, it is required to generate heading data. You can add remark-heading prior to remark-structure to generate heading IDs.',
          );
          return;
        }

        pending.push(() => {
          const content = s.inner(node).replace(headingIdRegex, '').trim();
          push({ id, code: headingIds?.[id], content }, conditions);
        });
      } else {
        pending.push(() => {
          const content = s.stringify(node).trim();
          if (content.length > 0) push({ heading: undefined, content }, conditions);
        });
      }
    },
    /** the structured data of the source: authored expressions as their source, the content of every branch */
    toStatic() {
      flush();
      const contents: string[] = [];
      for (const record of records) contents.push(out.toStatic(record.content));
      return toStructuredData(records, contents);
    },
    /**
     * The code of the records that show for the props of a page, a function of the props: see `structured-data.ts`.
     * `undefined` when they read no props, they are the static records.
     */
    toCode(scope: () => ReadonlySet<string>): string | undefined {
      flush();
      if (!dynamic) return;
      const items: { code: string; when: string[] }[] = [];
      for (const record of records) {
        let code = `{content: ${out.toCode(record.content)}`;
        if ('id' in record) code += `, id: ${record.code ?? JSON.stringify(record.id)}`;
        else {
          if (record.heading !== undefined) code += `, heading: ${JSON.stringify(record.heading)}`;
          if (record.table) code += `, table: ${JSON.stringify(record.table)}`;
        }
        items.push({ code: `${code}}`, when: record.when });
      }
      // the MDX components are page props, like in the content
      return listCode(items, true, out.componentsCode(scope, 'props.components'));
    },
  };
}

/**
 * Structured data from its records in document order and their content as text: content goes under the last heading
 * before it, records are trimmed and empty ones are left out.
 */
export function toStructuredData(
  records: readonly { id?: string; heading?: string; table?: string }[],
  contents: string[],
) {
  const data = {
    contents: [] as StructuredContent[],
    headings: [] as { id: string; content: string }[],
  };
  let heading: string | undefined;
  for (let i = 0; i < records.length; i++) {
    const { id, table, heading: own = heading } = records[i];
    const content = contents[i].trim();
    if (id !== undefined) heading = id;
    if (!content) continue;
    if (id !== undefined) data.headings.push({ id, content });
    else data.contents.push(table ? { heading: own, content, table } : { heading: own, content });
  }
  return data;
}
