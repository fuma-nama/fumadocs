import type { Transformer } from 'unified';
import type { Nodes, Root, RootContent } from 'mdast';
import { valueToEstree } from 'estree-util-value-to-estree';
import { removePosition } from 'unist-util-remove-position';
import { flattenNode, walk } from './mdast-utils';
import type { LLMsOptions } from 'fumadocs-core/mdx-plugins';
import { Parser } from 'acorn';
import type { MdxjsEsm } from 'mdast-util-mdx';
import { listCode } from '../../../../shared/code-output';
import { walkBranches } from '../../../../shared/show';
import { remarkLLMs } from 'fumadocs-core/mdx-plugins/remark-llms';

export interface ExtractedReference {
  href: string;
}

export interface PostprocessOptions {
  _format: 'md' | 'mdx';

  /**
   * Properties to export from `vfile.data`
   */
  valueToExport?: string[];

  /**
   * export the Markdown of documents via `_markdown`, generated by `remarkLLMs`.
   */
  includeProcessedMarkdown?: boolean | LLMsOptions;

  /**
   * extract link references, export via `extractedReferences`.
   */
  extractLinkReferences?: boolean;

  /**
   * store MDAST and export via `_mdast`.
   */
  includeMDAST?:
    | boolean
    | {
        removePosition?: boolean;
      };
}

/**
 * - collect references
 * - write frontmatter (auto-title & description)
 */
export function remarkPostprocess({
  includeProcessedMarkdown = false,
  includeMDAST = false,
  extractLinkReferences = false,
  valueToExport = [],
}: PostprocessOptions): Transformer<Root, Root> {
  return (tree, file) => {
    const frontmatter = (file.data.frontmatter ??= {});
    if (!frontmatter.title) {
      walk<Nodes>(tree, (node) => {
        if (node.type === 'heading' && node.depth === 1) {
          frontmatter.title = flattenNode(node);
          return false;
        }
      });
    }

    file.data['mdx-export'] ??= [];
    file.data['mdx-export'].push({
      name: 'frontmatter',
      value: frontmatter,
    });

    if (extractLinkReferences) {
      const items: { code: string; when: string[] }[] = [];
      walkBranches<Nodes>(tree, (node, when) => {
        if (node.type === 'link') items.push({ code: JSON.stringify({ href: node.url }), when });
      });
      tree.children.unshift({
        type: 'mdxjsEsm',
        value: '',
        data: {
          estree: Parser.parse(`export const extractedReferences = ${listCode(items, false)};`, {
            ecmaVersion: 'latest',
            sourceType: 'module',
          }) as unknown as NonNullable<MdxjsEsm['data']>['estree'],
        },
      });
    }

    if (includeProcessedMarkdown) {
      const options = typeof includeProcessedMarkdown === 'object' ? includeProcessedMarkdown : {};
      // the MDAST holds the export, which stays the component of pages that render for props
      const llms = remarkLLMs(
        includeMDAST && file.data.unstable_runtimeOutputs
          ? { ...options, output: options.output ?? 'function' }
          : options,
      );
      llms(tree, file, () => undefined);
    }

    if (includeMDAST) {
      const options = includeMDAST === true ? {} : includeMDAST;
      let serialized = tree;

      if (options.removePosition) {
        serialized = structuredClone(tree);
        removePosition(serialized); // mutates without returning anything
      }

      const mdast = JSON.stringify(serialized);

      file.data['mdx-export'].push({
        name: '_mdast',
        value: mdast,
      });
    }

    for (const { name, value } of file.data['mdx-export']) {
      tree.children.unshift(getMdastExport(name, value));
    }

    // reset the data to reduce memory usage
    file.data['mdx-export'] = [];

    for (const name of valueToExport) {
      if (!(name in file.data)) continue;

      tree.children.unshift(getMdastExport(name, file.data[name]));
    }
  };
}

/**
 * MDX.js first converts javascript (with esm support) into mdast nodes with remark-mdx, then handle the other remark plugins
 *
 * Therefore, if we want to inject an export, we must convert the object into AST, then add the mdast node
 */
function getMdastExport(name: string, value: unknown): RootContent {
  return {
    type: 'mdxjsEsm',
    value: '',
    data: {
      estree: {
        type: 'Program',
        sourceType: 'module',
        body: [
          {
            type: 'ExportNamedDeclaration',
            attributes: [],
            specifiers: [],
            source: null,
            declaration: {
              type: 'VariableDeclaration',
              kind: 'let',
              declarations: [
                {
                  type: 'VariableDeclarator',
                  id: {
                    type: 'Identifier',
                    name,
                  },
                  init: valueToEstree(value),
                },
              ],
            },
          },
        ],
      },
    },
  };
}
