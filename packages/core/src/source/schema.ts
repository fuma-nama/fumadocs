import { z } from 'zod';

const staticParams = z.array(z.record(z.string(), z.string())).optional();

/**
 * Zod 4 schema
 */
export const metaSchema = z.object({
  staticParams,
  title: z.string().optional(),
  pages: z.array(z.string()).optional(),
  /** specify a index page for folder */
  pagesIndex: z.string().optional(),
  description: z.string().optional(),
  root: z.union([z.boolean(), z.string()]).optional(),
  defaultOpen: z.boolean().optional(),
  collapsible: z.boolean().optional(),
  icon: z.string().optional(),
});

export type _JSONType =
  | number
  | boolean
  | string
  | null
  | _JSONType[]
  | {
      [key: string]: _JSONType;
    };
/**
 * Zod 4 schema
 */
export const pageSchema = z.object({
  staticParams,
  title: z.string(),
  description: z.string().optional(),
  icon: z.string().optional(),
  full: z.boolean().optional(),

  // generated by Fumadocs OpenAPI & AsyncAPI
  _openapi: z.record(z.string(), z.custom<_JSONType>()).optional(),
  _asyncapi: z.record(z.string(), z.custom<_JSONType>()).optional(),
});
