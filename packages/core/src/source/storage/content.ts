import { FileSystem } from '@/source/storage/file-system';
import { basename, dirname, extname, normalize } from '@/source/path';
import type { ResolvedLoaderConfig } from '../loader';
import { isStaticSource, MetaData, PageData, type Params, type StaticSource } from '../source';
import { fillParams, getStaticParams, isDynamicPath, segmentNames } from '../static-params';

export type ContentStorage<
  P extends ContentStoragePageFile = ContentStoragePageFile,
  M extends ContentStorageMetaFile = ContentStorageMetaFile,
> = FileSystem<P | M> & {
  /** always `undefined`, for inferring types only */
  $inferPage: P;
  /** always `undefined`, for inferring types only */
  $inferMeta: M;
};

/** @internal */
export interface ContentStorageMetaFile<
  Type extends string | undefined = string | undefined,
  Data extends MetaData = MetaData,
> {
  type: Type;
  path: string;
  absolutePath?: string;

  format: 'meta';
  data: Data;
}

/** @internal */
export interface ContentStoragePageFile<
  Type extends string | undefined = string | undefined,
  Data extends PageData = PageData,
> {
  type: Type;
  path: string;
  absolutePath?: string;

  format: 'page';
  slugs: string[];
  data: Data;
  /** for a page of a dynamic file, its params */
  params?: Params;
}

type ContentStorageFile = ContentStorageMetaFile | ContentStoragePageFile;

const EmptyLang = Symbol();

/**
 * convert input files into virtual file system.
 *
 * in the storage, locale codes are removed from file paths, hence the same file will have same file paths in every storage.
 */
export function createContentStorageBuilder(loaderConfig: ResolvedLoaderConfig) {
  const { input, plugins, i18n } = loaderConfig;

  let parser: (normalizedPath: string) => [string, string?] = (path) => [path];
  if (i18n && i18n.parser !== 'none') {
    const langSet = new Set(i18n.languages);

    parser = (path) => {
      let locale: string;
      let rest: string;
      if (i18n.parser === 'dir') {
        // `{locale}/file.ext`
        const slash = path.indexOf('/');
        if (slash <= 0) return [path];
        locale = path.slice(0, slash);
        rest = path.slice(slash + 1);
      } else {
        // `file.{locale}.ext`
        const ext = path.lastIndexOf('.');
        const dot = path.lastIndexOf('.', ext - 1);
        if (dot === -1 || dot < path.lastIndexOf('/')) return [path];
        locale = path.slice(dot + 1, ext);
        rest = path.slice(0, dot) + path.slice(ext);
      }

      if (locale === '$' || langSet.has(locale)) return [rest, locale];
      return [path];
    };
  }

  const fileMap = new Map<
    string | typeof EmptyLang,
    [storageKey: string, file: ContentStorageFile][]
  >();

  function add(storageKey: string, locale: string | typeof EmptyLang, file: ContentStorageFile) {
    const entry = [storageKey, file] as const;
    if (i18n && locale === '$') {
      for (const item of i18n.languages) pushMapList(fileMap, item, entry);
    } else {
      pushMapList(fileMap, locale, entry);
    }
  }

  /** the meta files of dynamic folders that give their data at the params of each folder */
  const metaDataAt = new Map<ContentStorageMetaFile, (params: Params) => MetaData>();

  function scan(type: string | undefined, source: StaticSource) {
    const staticParams = new Map<string, Params[] | undefined>();
    const readStaticParams = (path: string) => staticParams.get(path);
    for (const inputFile of source.files) {
      if (inputFile.type !== 'meta') continue;
      const path = normalize(
        source.baseDir ? `${source.baseDir}/${inputFile.path}` : inputFile.path,
      );
      staticParams.set(
        path.slice(0, path.length - extname(path).length),
        inputFile.data.staticParams,
      );
    }

    for (const inputFile of source.files) {
      let file: ContentStorageMetaFile | ContentStoragePageFile;
      const path = normalize(
        source.baseDir ? `${source.baseDir}/${inputFile.path}` : inputFile.path,
      );
      let files: ContentStorageFile[] | undefined;

      if (inputFile.type === 'page') {
        file = {
          format: 'page',
          type,
          path,
          // will be generated by the slugs plugin if unspecified
          slugs: inputFile.slugs as string[],
          data: inputFile.data,
          absolutePath: inputFile.absolutePath,
        };
        const page = file;
        files = getStaticParams(path, {
          staticParams: inputFile.data.staticParams,
          readStaticParams,
        })?.map((params) => ({ ...page, params, data: inputFile.dataAt?.(params) ?? page.data }));
      } else {
        file = {
          format: 'meta',
          type,
          path,
          absolutePath: inputFile.absolutePath,
          data: inputFile.data,
        };
        if (inputFile.dataAt) metaDataAt.set(file, inputFile.dataAt);
      }

      const [storageKey, locale = i18n ? i18n.defaultLanguage : EmptyLang] =
        i18n && inputFile.locale ? [path, inputFile.locale] : parser(path);
      if (files) for (const item of files) add(storageKey, locale, item);
      else add(storageKey, locale, file);
    }
  }

  if (isStaticSource(input)) {
    scan(undefined, input);
  } else {
    for (const k in input) scan(k, input[k]);
  }

  // dynamic folder -> the folders that pages of every language fill with their params, the meta files of each language go there
  const folders = new Map<string, Map<string, Params>>();
  for (const list of fileMap.values())
    for (const [path, file] of list) {
      if (file.format !== 'page' || !file.params) continue;
      for (let folder = dirname(path); isDynamicPath(folder); folder = dirname(folder)) {
        let filled = folders.get(folder);
        if (!filled) folders.set(folder, (filled = new Map()));
        const target = fillParams(folder, file.params);
        if (filled.has(target)) continue;
        const params: Params = {};
        for (const name of segmentNames(folder)) params[name] = file.params[name];
        filled.set(target, params);
      }
    }
  for (const [locale, list] of fileMap) {
    if (folders.size === 0 && !list.some(([path]) => isDynamicPath(path))) continue;
    fileMap.set(locale, route(list, folders, metaDataAt));
  }

  function makeStorage(locale: string | typeof EmptyLang, inherit?: ContentStorage) {
    const storage = new FileSystem(inherit) as ContentStorage;
    for (const [storageKey, file] of fileMap.get(locale) ?? []) {
      storage.write(storageKey, file);
    }

    const context = { storage };
    for (const plugin of plugins) {
      plugin.transformStorage?.(context);
    }

    return storage;
  }

  return {
    i18n(): Record<string, ContentStorage> {
      const storages: Record<string, ContentStorage> = {};
      if (!i18n) return storages;

      const fallbackLang =
        i18n.fallbackLanguage !== null ? (i18n.fallbackLanguage ?? i18n.defaultLanguage) : null;

      function scan(lang: string): ContentStorage {
        if (storages[lang]) return storages[lang];

        return (storages[lang] = makeStorage(
          lang,
          fallbackLang && fallbackLang !== lang ? scan(fallbackLang) : undefined,
        ));
      }

      for (const lang of i18n.languages) scan(lang);
      return storages;
    },
    single(): ContentStorage {
      return makeStorage(EmptyLang);
    },
  };
}

function pushMapList<K, V>(map: Map<K, V[]>, k: K, v: V) {
  let list = map.get(k);
  if (!list) {
    list = [];
    map.set(k, list);
  }
  list.push(v);
}

/**
 * Route the files of dynamic paths: a page goes to the path its `params` fill, the meta file of a dynamic folder to
 * each folder that pages fill. Files at a static path win.
 */
function route(
  list: [string, ContentStorageFile][],
  folders: Map<string, Map<string, Params>>,
  metaDataAt: Map<ContentStorageMetaFile, (params: Params) => MetaData>,
): [string, ContentStorageFile][] {
  const out = new Map<string, ContentStorageFile>();
  for (const [path, file] of list) if (!isDynamicPath(path)) out.set(path, file);
  /** the path of a page or meta file -> its dynamic file */
  const made = new Map<string, string>();
  for (const [path, file] of list) {
    if (!isDynamicPath(path)) continue;
    const targets: [string, ContentStorageFile][] = [];
    if (file.format === 'page' && file.params) targets.push([fillParams(path, file.params), file]);
    if (file.format === 'meta') {
      const dataAt = metaDataAt.get(file);
      for (const [folder, params] of folders.get(dirname(path)) ?? [])
        targets.push([
          `${folder}/${basename(path)}`,
          dataAt ? { ...file, data: dataAt(params) } : file,
        ]);
    }
    if (targets.length === 0) out.set(path, file);

    for (const [target, item] of targets) {
      const other = made.get(target);
      if (other) throw new Error(`"${other}" and "${path}" both go to "${target}"`);
      if (out.has(target)) continue;
      made.set(target, path);
      out.set(target, item);
    }
  }

  return [...out];
}
